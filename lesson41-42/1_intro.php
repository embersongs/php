1. Безопасность приложений, а не окружения
2. Обеспечить безопасность:
    - конфиденциальность данных;
    - целостность данных
    - доступность приложения;
3. Кто атакует:
    - случайный пользователь;
    - бот;
    - злоумышленник;
    - конкурент;
    - сотрудник;
4. Как атакует, источник? - данные:
    GET, POST, cookie, headers, files, api ...


Общие правила:
1. не доверять пользовательскому вводу;
2. валидировать данные;
3. экранировать вывод;
4. использовать подготовленные SQL-запросы;
5. применять принцип минимальных привилегий;
6. хранить секреты в переменных окружения, а не в репозитории;
7. регулярно обновлять PHP и зависимости;
8. использовать безопасные настройки PHP (open_basedir, отключение опасных функций при необходимости, разумные лимиты памяти и времени выполнения);
9. вести журналирование событий безопасности;
10. выполнять регулярное резервное копирование.