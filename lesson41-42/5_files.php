 Основные угрозы
1. Загрузка PHP-скрипта

Самый опасный сценарий.

Допустим, пользователь может загрузить файл в папку /uploads.

Злоумышленник загружает:

shell.php

Содержимое:

<?php
system($_GET['cmd']);
?>
После загрузки открывает:

https://site.com/uploads/shell.php?cmd=whoami

Если веб-сервер выполняет PHP в каталоге загрузок, злоумышленник получает удаленное выполнение команд (Remote Code Execution).

Последствия
полный контроль над сервером;
чтение базы данных;
удаление файлов;
установка бэкдоров;
использование сервера для дальнейших атак.

2. Подмена расширения

Многие приложения проверяют только имя файла:

if ($extension == "jpg")

Злоумышленник может загрузить:

virus.php.jpg

или

shell.php.jpeg

или

avatar.jpg.php

В зависимости от конфигурации сервера такой файл может быть выполнен как PHP.

3. Подмена MIME-типа

Некоторые разработчики проверяют:

$_FILES['type']

Например:

if ($_FILES['type'] == "image/jpeg")

Но это значение присылает сам браузер.

Его легко изменить:

Content-Type: image/jpeg

при том что файл содержит PHP-код.

Поэтому $_FILES['type'] нельзя считать надежным.

4. Маскировка вредоносного содержимого

Файл может называться:

cat.jpg

но содержать:

<?php
//...
?>
Расширение — не гарантия безопасности.

5. SVG с JavaScript

SVG — это XML-документ.

Он может содержать:

<script>
alert(document.cookie)
</script>

Если такой SVG открыть в браузере, код может выполниться, что приведет к XSS.

6. HTML-файл

Пользователь загружает:

index.html

Внутри:

<script>
fetch(...)
</script>

Если сайт раздает HTML-файлы без ограничений, злоумышленник может использовать их для фишинга или выполнения сценариев в контексте домена.

7. ZIP-бомбы

Файл весит:

5 КБ

После распаковки:

100 ГБ

Это приводит к переполнению диска или отказу в обслуживании (DoS).

8. Изображения с вредоносными данными

Файл действительно является изображением, но содержит:

встроенные скрипты;
вредоносные EXIF-данные;
специально сформированные структуры для эксплуатации уязвимостей библиотек обработки изображений.

Такие атаки могут быть опасны, если приложение автоматически обрабатывает изображения.

9. Перезапись существующих файлов

Если использовать исходное имя:

move_uploaded_file(
    ...,
    "uploads/" . $_FILES['name']
);

то злоумышленник может загрузить:

logo.png

и заменить существующий файл.

10. Directory Traversal через имя файла

Попытка загрузить файл с именем:

../../config.php

или

../../../index.php

Если приложение не очищает имя файла, возможна запись за пределы каталога загрузок.

Что обязательно проверять
1. Проверка ошибок загрузки
if ($_FILES['file']['error'] !== UPLOAD_ERR_OK) {
throw new RuntimeException('Ошибка загрузки');
}
2. Ограничение размера

Например:

if ($_FILES['file']['size'] > 5 * 1024 * 1024) {
die("Файл слишком большой");
}

Это защищает от переполнения диска и чрезмерного потребления ресурсов.

3. Проверка MIME через finfo

Правильно:

$finfo = new finfo(FILEINFO_MIME_TYPE);

$mime = $finfo->file($_FILES['file']['tmp_name']);

Например:

image/jpeg
image/png
application/pdf

А не:

$_FILES['type']
4. Проверка расширения

Допускайте только белый список:

[
'jpg',
'jpeg',
'png',
'gif'
]

Запрещайте:

php
phtml
phar
cgi
pl
exe
sh
bat
5. Проверка содержимого

Для изображений можно использовать:

getimagesize()

или

exif_imagetype()

Они анализируют структуру файла, а не только его имя.

6. Генерация нового имени

Никогда не используйте имя пользователя.

Плохо:

avatar.jpg

Лучше:

8f4b3e8d-91a2-4e2c-a1f7.jpg

или

bin2hex(random_bytes(16))
7. Хранение вне public

Лучше:

/var/uploads/

а не:

/var/www/html/uploads/

Тогда загруженный файл нельзя открыть напрямую через браузер.

8. Запрет выполнения скриптов

Если хранить файлы внутри public, нужно отключить выполнение PHP в каталоге загрузок.

Например, для Nginx:

location /uploads/ {
location ~ \.php$ {
deny all;
}
}
9. Проверка допустимых символов

Имя файла не должно содержать:

/
\
..
%
NULL

Используйте только безопасные символы или вовсе не используйте оригинальное имя.

10. Ограничение количества файлов

Это помогает предотвратить заполнение диска злоумышленником.
